import os
from typing import Any, Literal, Optional

import ase
from pydantic import Field

try:
    from rdkit import Chem
    from rdkit.Chem import AllChem
    _RDKIT_AVAILABLE = True
except Exception:
    Chem = None
    AllChem = None
    _RDKIT_AVAILABLE = False

from cloudra.fs_utils import atomic_write_text
from cloudra.session_class import Session
from cloudra.tools_class import Tool, input_schema, output_schema

description = (
    "根据分子来源、计算方法、基组等参数自动生成完整的 Gaussian 输入文件（.gjf）并保存到指定目录；"
    "坐标从文件或 SMILES 自动生成，不会出现在返回结果中。"
    "适用：准备 Gaussian 计算输入（结构优化、频率、过渡态搜索等），之后可交 submit_compute_job 提交执行。"
    "不适用：解析计算结果（用 log_parser）、已有结构文件的格式互换（用 format_converter）。"
)


class GjfWriter_input_schema(input_schema):
    source_type: Literal["smiles", "xyz_file", "mol_file"] = Field(
        description="分子结构来源类型。"
                    "'smiles': 从 SMILES 字符串生成 3D 坐标；"
                    "'xyz_file': 从 .xyz 文件读取坐标；"
                    "'mol_file': 从 .mol 文件读取坐标。"
    )
    source_value: str = Field(
        description="分子结构来源值。"
                    "当 source_type='smiles' 时为 SMILES 字符串（如 'CC(=O)O'）；"
                    "当 source_type='xyz_file' 或 'mol_file' 时为文件的绝对路径。"
    )
    method: str = Field(
        default="b3lyp",
        description="计算方法，如 'b3lyp', 'hf', 'mp2', 'wb97xd', 'pbe0' 等。"
    )
    basis_set: str = Field(
        default="6-31g(d)",
        description="基组，如 '6-31g(d)', '6-311+g(d,p)', 'def2tzvp', 'cc-pvdz' 等。"
    )
    task_type: list[dict] = Field(
        default=[{"opt": None}],
        description='''计算任务类型为键，具体参数为值的字典列表。
                    示例：[{"opt":"TS,calcfc,noeigen"},{"freq":None}]'''
    )

    charge: int = Field(
        default=0,
        description="分子电荷。"
    )
    multiplicity: int = Field(
        default=1,
        description="自旋多重度。单重态=1, 双重态=2, 三重态=3。"
    )
    mem: str = Field(
        default="4GB",
        description="分配给 Gaussian 的内存，如 '4GB', '8GB'。"
    )
    nproc: int = Field(
        default=4,
        description="并行计算的 CPU 核心数。"
    )
    extra_keywords: Optional[str] = Field(
        default=None,
        description="附加的 Route Section 关键字，如 'scrf=(solvent=water)', 'empiricaldispersion=gd3bj' 等。"
    )
    title: str = Field(
        default="Gaussian job generated by Cloudra",
        description="任务描述标题。"
    )
    end_setting: str = Field(
        default="",
        description="在文件末尾增加的设置，比如混合基组，比如扫描设置等等"
                    "示例：B 1 34 S 15 0.02"
    )
    output_dir: str = Field(
        description=".gjf 文件的绝对路径（包含文件名）。"
    )
    chk_name: Optional[str] = Field(
        default=None,
        description="chk文件名。如H2O.chk"
    )
    rwf_name: Optional[str] = Field(
        default=None,
        description="rwf文件名，为高斯的临时文件，较大。"
    )
    fchk_name: Optional[str] = Field(
        default=None,
        description="fchk文件名。"
    )


class GjfWriter_output_schema(output_schema):
    is_success: bool = Field(description="文件生成是否成功")
    gjf_path: str = Field(default="", description="生成的 .gjf 文件绝对路径")
    message: str = Field(default="", description="状态或错误信息")


class GjfWriter(Tool):
    tool_id: str = 't-20'
    tool_name: str = 'gjf_writer'
    tool_description: str = description
    input_schema: Any = GjfWriter_input_schema
    output_schema: Any = GjfWriter_output_schema

    def is_write(self) -> bool:
        return True

    @staticmethod
    def _get_coordinates(source_type: str, source_value: str) -> str:
        """根据来源类型返回 Gaussian 格式的坐标文本。"""
        if source_type == "smiles":
            mol = Chem.MolFromSmiles(source_value)
            if mol is None:
                raise ValueError(f"无法从 SMILES 解析分子: {source_value}")
            mol = Chem.AddHs(mol)
            AllChem.EmbedMolecule(mol, randomSeed=42)
            AllChem.MMFFOptimizeMolecule(mol)
            xyz_block = Chem.MolToXYZBlock(mol)
            # XYZ 格式前两行为原子数与标题，从第三行开始为坐标
            return "\n".join(xyz_block.strip().split("\n")[2:])

        # xyz_file / mol_file 统一通过 ase 读取
        atoms = ase.io.read(source_value)
        lines = []
        for symbol, position in zip(atoms.symbols, atoms.positions):
            x, y, z = position
            lines.append(f"{symbol:<4} {x:>14.8f} {y:>14.8f} {z:>14.8f}")
        return "\n".join(lines)

    @staticmethod
    def _build_link0(user_input: GjfWriter_input_schema) -> str:
        """拼装 Link0 段。"""
        parts = []
        link0_map = {
            "chk": user_input.chk_name,
            "rwf": user_input.rwf_name,
            "fchk": user_input.fchk_name,
            "nproc": user_input.nproc,
            "mem": user_input.mem,
        }
        for key, value in link0_map.items():
            if value:
                parts.append(f"%{key}={value}")
        return "\n".join(parts)

    @staticmethod
    def _build_route(user_input: GjfWriter_input_schema) -> str:
        """拼装 Route 段。"""
        keywords = ["#p"]

        for task in user_input.task_type:
            for key, value in task.items():
                if value is None:
                    keywords.append(key)
                elif "," in str(value):
                    keywords.append(f"{key}=({value})")
                else:
                    keywords.append(f"{key}={value}")

        keywords.append(f"{user_input.method}/{user_input.basis_set}")

        if user_input.extra_keywords:
            keywords.append(user_input.extra_keywords)

        return " ".join(keywords)

    @staticmethod
    def _build_gjf(user_input: GjfWriter_input_schema, coords: str) -> str:
        """拼装完整的 .gjf 文本。

        Gaussian 要求坐标块后有一个空行作为输入结束标记，
        因此末尾统一保留一个空行。
        """
        link0 = GjfWriter._build_link0(user_input)
        route = GjfWriter._build_route(user_input)

        sections = [
            link0,
            route,
            "",                    # Route 后空行
            user_input.title,
            "",                    # Title 后空行
            f"{user_input.charge} {user_input.multiplicity}",
            coords,
            "",                    # 坐标后空行（Gaussian 输入结束标记）
        ]

        if user_input.end_setting:
            # 在结束空行之前插入自定义设置及其后的空行
            sections.insert(-1, user_input.end_setting)
            sections.insert(-1, "")

        return "\n".join(sections) + "\n"

    async def tool_call(self, user_input: GjfWriter_input_schema, session: Session) -> GjfWriter_output_schema:
        if not _RDKIT_AVAILABLE:
            return GjfWriter_output_schema(
                is_success=False,
                gjf_path="",
                message="环境未安装 RDKit 库，无法生成 Gaussian 输入文件。请执行: pip install 'cloudra[chem]'"
            )
        try:
            coords = self._get_coordinates(user_input.source_type, user_input.source_value)
            gjf_content = self._build_gjf(user_input, coords)

            output_dir = os.path.dirname(user_input.output_dir)
            if output_dir:
                os.makedirs(output_dir, exist_ok=True)
            gjf_path = user_input.output_dir

            atomic_write_text(gjf_path, gjf_content)

            return GjfWriter_output_schema(
                is_success=True,
                gjf_path=gjf_path,
                message="Gaussian 输入文件生成成功。"
            )
        except Exception as e:
            return GjfWriter_output_schema(
                is_success=False,
                gjf_path="",
                message=f"生成失败: {str(e)}"
            )


def get_class():
    return GjfWriter
