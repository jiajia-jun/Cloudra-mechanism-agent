#!/usr/bin/env python3
"""Create a desktop entry for this source checkout; application startup stays in web.sh."""

from __future__ import annotations

import os
import platform
import shlex
import shutil
import subprocess
from pathlib import Path


def _desktop_value(value: Path) -> str:
    return str(value).replace("\\", "\\\\").replace("\n", "\\n").replace("\r", "\\r").replace("\t", "\\t")


def _desktop_exec(path: Path) -> str:
    value = str(path).replace("%", "%%")
    for char in ("\\", '"', "`", "$"):
        value = value.replace(char, "\\" + char)
    return '"' + value.replace("\\", "\\\\") + '"'


def create_shortcut(project: Path) -> None:
    project = project.resolve()
    system = platform.system()
    if system not in {"Darwin", "Linux"}:
        raise RuntimeError("Use the native Windows installer on the windows branch.")
    node = shutil.which("node")
    if node is None:
        raise RuntimeError("Install Node.js >= 22.12, then run this command again.")
    python = project / ".venv/bin/python"
    node_bin = str(Path(node).parent)
    launcher = project / ".venv/bin/cloudra-ui"
    launcher.parent.mkdir(parents=True, exist_ok=True)
    content = (
        "#!/bin/bash\n"
        "# Generated by Cloudra; run create_desktop_shortcut.py again after moving the folder.\n"
        f"export PATH={shlex.quote(node_bin)}:\"$PATH\"\n"
        f"export CLOUDRA_PYTHON={shlex.quote(str(python))}\n"
        f"/bin/bash {shlex.quote(str(project / 'web.sh'))} \"$@\"\n"
        "status=$?\n"
        'if [ "$status" -ne 0 ]; then\n'
        "  printf '\\nCloudra could not start. See the error above.\\n'\n"
        '  if [ -t 0 ]; then read -r -p "Press Enter to close... "; fi\n'
        "fi\n"
        'exit "$status"\n'
    )
    launcher.write_text(content, encoding="utf-8")
    launcher.chmod(0o755)
    home_dir = Path.home()
    if system == "Darwin":
        desktop = home_dir / "Desktop"
        desktop.mkdir(exist_ok=True)
        shortcut = desktop / "Cloudra.command"
        shortcut.write_text(content, encoding="utf-8")
        shortcut.chmod(0o755)
        print(f"Desktop shortcut: {shortcut}")
        return

    applications = Path(os.environ.get("XDG_DATA_HOME") or home_dir / ".local/share") / "applications"
    applications.mkdir(parents=True, exist_ok=True)
    entry = applications / "cloudra.desktop"
    entry.write_text(
        "[Desktop Entry]\nType=Application\nName=Cloudra\n"
        "Comment=Open the Cloudra research interface\n"
        f"Exec={_desktop_exec(launcher)}\n"
        f"Path={_desktop_value(project)}\n"
        f"Icon={_desktop_value(project / 'docs/assets/Cloudra-logo.svg')}\n"
        "Terminal=true\nCategories=Education;Science;Chemistry;\n",
        encoding="utf-8",
    )
    entry.chmod(0o755)
    print(f"Application menu entry: {entry}")
    desktop = home_dir / "Desktop"
    xdg = shutil.which("xdg-user-dir")
    if xdg:
        result = subprocess.run([xdg, "DESKTOP"], capture_output=True, text=True, check=False)
        if result.returncode == 0 and result.stdout.strip():
            desktop = Path(result.stdout.strip())
    if desktop.is_dir() and desktop != home_dir:
        shortcut = desktop / "Cloudra.desktop"
        shutil.copyfile(entry, shortcut)
        shortcut.chmod(0o755)
        print(f"Desktop shortcut: {shortcut} (choose Allow Launching if prompted)")
    else:
        print("No desktop folder found; open Cloudra from the application menu or run bash web.sh.")


if __name__ == "__main__":
    create_shortcut(Path(__file__).resolve().parents[1])
